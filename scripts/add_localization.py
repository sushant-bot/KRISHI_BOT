APPLY_METHOD = '''
  applyLanguageToDom() {
    const lang = this.currentLanguage;
    document.documentElement.setAttribute('lang', lang);

    // Update textContent for data-i18n
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const val = this.t(key);
      if (val && val !== key) {
        el.textContent = val;
      }
    });

    // Update innerHTML for data-i18n-html
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      const val = this.t(key);
      if (val && val !== key) {
        el.innerHTML = val;
      }
    });

    // Update placeholder for data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.t(key);
      if (val && val !== key) {
        el.placeholder = val;
      }
    });

    // Update title for data-i18n-title
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      const val = this.t(key);
      if (val && val !== key) {
        el.title = val;
        el.setAttribute('aria-label', val);
      }
    });
  }
'''

def update_translation_service():
    path = r'frontend/src/translationService.js'
    with open(path, 'r', encoding='utf-8') as f:
        content = f.read()

    # Find the end of LOCAL_DICTIONARY
    target = "  'flow_failure_title': {"
    if target in content and "'brand_title':" not in content:
        # Find closing brace of LOCAL_DICTIONARY
        idx = content.find("  'flow_failure_title': {")
        close_idx = content.find("};\n\nclass TranslationService {", idx)
        if close_idx != -1:
            part1 = content[:close_idx] + "," + DICTIONARY_ENTRIES + "\n};\n\nclass TranslationService {"
            part2 = content[close_idx + len("};\n\nclass TranslationService {"):]
            
            # Now add applyLanguageToDom into TranslationService
            constructor_end = "    this.listeners = [];\n  }"
            if constructor_end in part2:
                part2 = part2.replace(constructor_end, constructor_end + "\n" + APPLY_METHOD, 1)

            new_content = part1 + part2
            with open(path, 'w', encoding='utf-8') as f:
                f.write(new_content)
            print("Successfully updated translationService.js")
        else:
            print("Could not find closing brace of LOCAL_DICTIONARY")
    else:
        print("Dictionary already contains brand_title or target not found")

