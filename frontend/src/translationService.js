  /**
   * Translates a static dictionary key with offline resilience.
   */
  t(key, fallback = '') {
    const lang = this.currentLanguage;
    if (LOCAL_DICTIONARY[key]) {
      return LOCAL_DICTIONARY[key][lang] || LOCAL_DICTIONARY[key]['en'] || fallback;
    }
    return fallback || key;
  }

  /**
   * Translates arbitrary text using cache -> backend /api/translate -> offline dictionary -> fallback.
   */
  async translateText(text, targetLang = null) {
    const lang = targetLang || this.currentLanguage;
    const clean = String(text || '').trim();
    if (!clean || lang === 'en') return clean;

    const cacheKey = `${clean.toLowerCase()}_en_${lang}`;
    if (this.cache[cacheKey]) {
      return this.cache[cacheKey];
    }

    // Try backend translation endpoint
    try {
      const resp = await fetch('/api/translate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          text: clean,
          source_lang: 'en',
          target_lang: lang,
        }),
      });

      if (resp.ok) {
        const data = await resp.json();
        if (data.translated_text) {
          this.cache[cacheKey] = data.translated_text;
          this.saveCache();
          return data.translated_text;
        }
      }
    } catch (err) {
      console.warn('Backend translation unavailable, using offline dictionary:', err);
    }

    // Check local dictionary values
    for (const item of Object.values(LOCAL_DICTIONARY)) {
      if (item.en && item.en.toLowerCase() === clean.toLowerCase() && item[lang]) {
        return item[lang];
      }
    }

    return clean;
  }

